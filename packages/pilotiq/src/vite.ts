/**
 * Source-module info for the manifest. The plugin imports each panel
 * module, finds the exported `Pilotiq` instances by name, and the
 * client-side manifest re-imports those names + walks the runtime
 * config to collect class refs at module init.
 *
 * No need to re-export every class from the panel module — they're
 * reachable through the panel's `getConfig()` chain at runtime.
 */
interface PanelExport {
  exportName: string
  importPath: string
}

/**
 * Resolve panel-path strings against the project root and import each.
 * Returns the panels (Pilotiq instances) and the absolute resolved file
 * path for each — needed so we can compute relative re-export paths.
 */
/**
 * Discover Pilotiq-instance exports across the configured panel modules.
 * Returns `{ exportName, importPath }` for each so the client-side
 * manifest can re-import them by name.
 */
async function discoverPanelExports(
  panelPaths: string[],
  projectRoot: string,
): Promise<PanelExport[]> {
  // jiti gives us a Node-compatible loader that handles .ts/.tsx, ESM,
  // and TypeScript syntax. `fsCache: false` + a fresh instance per
  // call ensures HMR-style regeneration picks up edits.
  const jiti = createJiti(projectRoot, { fsCache: false, moduleCache: false })
  const out: PanelExport[] = []
  for (const userPath of panelPaths) {
    const resolved = await resolvePanelPath(userPath, projectRoot)
    if (!resolved) continue
    try {
      const mod = await jiti.import(resolved) as Record<string, unknown>
      for (const [name, value] of Object.entries(mod)) {
        if (looksLikePilotiq(value)) out.push({ exportName: name, importPath: resolved })
      }
    } catch (err) {
      const msg = err instanceof Error ? err.message : String(err)
      throw new Error(
        `[pilotiq vite plugin] Failed to import panel module "${userPath}" (resolved to "${resolved}"): ${msg}\n` +
          `Panel files must be import-safe — top-level code must not run server-only logic.`,
      )
    }
  }
  return out
}

async function resolvePanelPath(userPath: string, projectRoot: string): Promise<string | null> {
  const candidates = [userPath, userPath + '.ts', userPath + '.tsx', userPath + '.js', userPath + '.mjs']
  for (const c of candidates) {
    const abs = path.isAbsolute(c) ? c : path.resolve(projectRoot, c)
    if (fs.existsSync(abs) && fs.statSync(abs).isFile()) return abs
  }
  return null
}

function looksLikePilotiq(value: unknown): boolean {
  if (!value || typeof value !== 'object') return false
  const v = value as { getConfig?: unknown }
  return typeof v.getConfig === 'function'
}

/**
 * Write the component manifest. The manifest imports the user's
 * `Pilotiq` instances by name, walks their `getConfig()`, and stamps
 * every Resource/Global/Page class into a `componentRegistry` object
 * keyed by class name. Classes are reached through the panel's runtime
 * config, so the user doesn't need to re-export them from the panel
 * module.
 */
function writeComponentsManifest(panelExports: PanelExport[], pagesRoot: string): void {
  const outDir = path.join(pagesRoot, '(pilotiq)')
  fs.mkdirSync(outDir, { recursive: true })

  const lines = [
    '// AUTO-GENERATED by @pilotiq/pilotiq — do not edit.',
    '// Imports each registered Pilotiq instance and walks its config to',
    '// expose every Resource/Global/Page class as `componentRegistry[ClassName]`.',
    '// The renderer uses this to resolve component-typed icons.',
    '',
  ]

  if (panelExports.length === 0) {
    lines.push('// (no panels found — register classes via Pilotiq.make() in your panel module)')
    lines.push('export const componentRegistry: Record<string, unknown> = {}')
    lines.push('')
    writeIfChanged(path.join(outDir, '_components.ts'), lines.join('\n'))
    return
  }

  // Group exports by source path so we emit one import per file.
  const byPath = new Map<string, string[]>()
  for (const e of panelExports) {
    if (!byPath.has(e.importPath)) byPath.set(e.importPath, [])
    byPath.get(e.importPath)!.push(e.exportName)
  }
  for (const [absPath, names] of byPath) {
    let rel = path.relative(outDir, absPath).replace(/\\/g, '/')
    if (!rel.startsWith('.')) rel = './' + rel
    rel = rel.replace(/\.tsx?$/, '').replace(/\.jsx?$/, '')
    lines.push(`import { ${names.join(', ')} } from '${rel}'`)
  }

  const allExportNames = panelExports.map(e => e.exportName).join(', ')
  lines.push('')
  lines.push('const _all: Record<string, unknown> = {}')
  lines.push('function _add(c: any) { if (typeof c === \'function\' && c.name) _all[c.name] = c }')
  lines.push('function _walk(p: any) {')
  lines.push('  const cfg = p?.getConfig?.()')
  lines.push('  cfg?.resources?.forEach(_add)')
  lines.push('  cfg?.globals?.forEach(_add)')
  lines.push('  cfg?.pages?.forEach(_add)')
  lines.push('}')
  lines.push(`for (const _p of [${allExportNames}]) _walk(_p)`)
  lines.push('')
  lines.push('export const componentRegistry: Record<string, unknown> = _all')
  lines.push('')

  writeIfChanged(path.join(outDir, '_components.ts'), lines.join('\n'))
}

/**
 * Update the auto-gen `+Layout.tsx` template to import the manifest and
 * pass it to `AppShell`. Idempotent — overwrites on each run.
 */
function writeLayoutWithManifest(pagesRoot: string): void {
  const outDir = path.join(pagesRoot, '(pilotiq)')
  writeIfChanged(path.join(outDir, '+Layout.tsx'), `// AUTO-GENERATED by @pilotiq/pilotiq — do not edit.
import { usePageContext } from 'vike-react/usePageContext'
import { AppShell, ThemeProvider, generateThemeCSS, NavigateProvider } from '@pilotiq/pilotiq/react'
import { navigate as vikeNavigate } from 'vike/client/router'
import { componentRegistry } from './_components.js'
import type { ReactNode } from 'react'

// Wrap vike's async navigate so the NavigateProvider's fire-and-forget
// signature is satisfied. \`scrollToTop: false\` keeps the user's scroll
// position across SPA-only updates (filter changes, sort, pagination).
const navigate = (url: string): void => {
  void vikeNavigate(url, { scrollToTop: false } as any)
}

export default function PilotiqLayout({ children }: { children: ReactNode }) {
  const ctx = usePageContext() as unknown as { viewProps?: Record<string, unknown>; data?: Record<string, unknown>; urlPathname?: string }
  const { panel, basePath, layout, notifications } = (ctx.data ?? ctx.viewProps) as any ?? {}
  const currentPath = ctx.urlPathname
  if (!panel) return <NavigateProvider navigate={navigate}>{children}</NavigateProvider>

  // SSR: inject theme CSS inline to prevent FOUC
  const themeCss = panel.theme ? generateThemeCSS(panel.theme) : null

  return (
    <NavigateProvider navigate={navigate}>
      <ThemeProvider theme={panel.theme}>
        {themeCss && <style dangerouslySetInnerHTML={{ __html: themeCss }} />}
        <AppShell panel={panel} basePath={basePath} layout={layout} notifications={notifications} currentPath={currentPath} componentRegistry={componentRegistry as any}>
          {children}
        </AppShell>
      </ThemeProvider>
    </NavigateProvider>
  )
}
`)
}

