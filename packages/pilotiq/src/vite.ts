/**
 * Vite plugin that generates Vike page stubs for @pilotiq/pilotiq.
 *
 * Stubs are written at plugin construction time (before Vike scans pages/).
 * They use route functions that check PilotiqRegistry at request time, so
 * they work for any number of registered panels without regeneration.
 */
import fs from 'node:fs'
import path from 'node:path'
import type { Plugin } from 'vite'

function writeIfChanged(filePath: string, contents: string): void {
  fs.mkdirSync(path.dirname(filePath), { recursive: true })
  if (fs.existsSync(filePath)) {
    const existing = fs.readFileSync(filePath, 'utf8')
    if (existing === contents) return
  }
  fs.writeFileSync(filePath, contents)
}

function generatePages(pagesRoot: string): void {
  const outDir = path.join(pagesRoot, '(pilotiq)')

  // Shared config
  writeIfChanged(path.join(outDir, '+config.ts'), `// AUTO-GENERATED by @pilotiq/pilotiq — do not edit.
import type { Config } from 'vike/types'

export default {
  passToClient: ['viewProps'],
} satisfies Config
`)

  // Shared data stub
  const dataStub = `// AUTO-GENERATED by @pilotiq/pilotiq — do not edit.
import type { PageContextServer } from 'vike/types'
export const data = (_pageContext: PageContextServer): null => null
`

  // ── Head — FOUC prevention ────────────────────────────────
  const headContent = [
    '// AUTO-GENERATED by @pilotiq/pilotiq — do not edit.',
    "import { usePageContext } from 'vike-react/usePageContext'",
    '',
    '// Fontshare hosts Satoshi (Pilotiq brand font). Google Fonts is the fallback',
    '// for any other family configured via Pilotiq.theme({ fonts }).',
    'const FONTSHARE_FAMILIES: Record<string, string> = {',
    "  Satoshi: 'https://api.fontshare.com/v2/css?f[]=satoshi@300,500,700&display=swap',",
    '}',
    '',
    'export default function PilotiqHead() {',
    '  let fontFamilies: string[] = []',
    '',
    '  try {',
    '    const ctx = usePageContext() as unknown as { viewProps?: Record<string, unknown> }',
    '    const theme = (ctx.viewProps as any)?.panel?.theme',
    '    const fonts = theme?.fonts',
    '    if (fonts) {',
    '      const seen = new Set<string>()',
    '      if (fonts.body) seen.add(fonts.body)',
    '      if (fonts.heading && !seen.has(fonts.heading)) seen.add(fonts.heading)',
    '      fontFamilies = [...seen]',
    '    }',
    '  } catch {',
    '    // pageContext may not be available in all render contexts',
    '  }',
    '',
    '  const fontshareLinks: string[] = []',
    '  const googleFamilies: string[] = []',
    '  for (const family of fontFamilies) {',
    '    const fsHref = FONTSHARE_FAMILIES[family]',
    '    if (fsHref) fontshareLinks.push(fsHref)',
    '    else        googleFamilies.push(family)',
    '  }',
    '',
    '  const googleHref = googleFamilies.length > 0',
    '    ? `https://fonts.googleapis.com/css2?${googleFamilies.map((f: string) => `family=${f.replace(/ /g, \'+\')}:wght@400;500;600;700`).join(\'&\')}&display=swap`',
    '    : null',
    '',
    '  return (',
    '    <>',
    '      {fontshareLinks.length > 0 && (',
    '        <link rel="preconnect" href="https://api.fontshare.com" crossOrigin="" />',
    '      )}',
    '      {fontshareLinks.map((href: string) => (',
    '        <link key={href} rel="stylesheet" href={href} />',
    '      ))}',
    '      {googleHref && (',
    '        <>',
    '          <link rel="preconnect" href="https://fonts.googleapis.com" />',
    '          <link rel="preconnect" href="https://fonts.gstatic.com" crossOrigin="" />',
    '          <link rel="stylesheet" href={googleHref} />',
    '        </>',
    '      )}',
    '      <script',
    '        dangerouslySetInnerHTML={{',
    "          __html: `(function(){try{var t=localStorage.getItem('pilotiq-theme');if(t==='dark'||(t!=='light'&&matchMedia('(prefers-color-scheme:dark)').matches)){document.documentElement.classList.add('dark')}}catch(e){}})()`",
    '        }}',
    '      />',
    '    </>',
    '  )',
    '}',
  ].join('\n')
  writeIfChanged(path.join(outDir, '+Head.tsx'), headContent + '\n')

  // ── Layout — persists across page navigations ────────────
  writeIfChanged(path.join(outDir, '+Layout.tsx'), `// AUTO-GENERATED by @pilotiq/pilotiq — do not edit.
import { usePageContext } from 'vike-react/usePageContext'
import { AppShell, ThemeProvider, generateThemeCSS } from '@pilotiq/pilotiq/react'
import type { ReactNode } from 'react'

export default function PilotiqLayout({ children }: { children: ReactNode }) {
  const ctx = usePageContext() as unknown as { viewProps?: Record<string, unknown> }
  const { panel, basePath, layout } = ctx.viewProps as any ?? {}
  if (!panel) return <>{children}</>

  // SSR: inject theme CSS inline to prevent FOUC
  const themeCss = panel.theme ? generateThemeCSS(panel.theme) : null

  return (
    <ThemeProvider theme={panel.theme}>
      {themeCss && <style dangerouslySetInnerHTML={{ __html: themeCss }} />}
      <AppShell panel={panel} basePath={basePath} layout={layout}>
        {children}
      </AppShell>
    </ThemeProvider>
  )
}
`)

  // ── Dashboard ────────────────────────────────────────────
  writeIfChanged(path.join(outDir, 'dashboard', '+route.ts'), `// AUTO-GENERATED by @pilotiq/pilotiq — do not edit.
import type { RouteSync } from 'vike/types'
import { PilotiqRegistry } from '@pilotiq/pilotiq/registry'

export const route: RouteSync = (pageContext) => {
  const parts = pageContext.urlPathname.split('/').filter(Boolean)
  if (parts.length !== 1) return false
  if (import.meta.env.SSR && !PilotiqRegistry.findByPath('/' + parts[0])) return false
  return { routeParams: { basePath: parts[0] } }
}
`)
  writeIfChanged(path.join(outDir, 'dashboard', '+data.ts'), dataStub)
  writeIfChanged(path.join(outDir, 'dashboard', '+Page.tsx'), `// AUTO-GENERATED by @pilotiq/pilotiq — do not edit.
import { usePageContext } from 'vike-react/usePageContext'
import { SchemaRenderer } from '@pilotiq/pilotiq/react'

export default function PilotiqDashboard() {
  const ctx = usePageContext() as unknown as { viewProps?: Record<string, unknown> }
  const { panel, basePath, schemaData } = ctx.viewProps as any ?? {}
  const hasSchema = schemaData && schemaData.length > 0

  if (hasSchema) return <SchemaRenderer elements={schemaData} />

  return (
    <>
      <h1 className="text-2xl font-bold mb-6">
        {panel?.branding?.title ?? panel?.name} Dashboard
      </h1>
      <div className="grid grid-cols-1 md:grid-cols-2 lg:grid-cols-3 gap-4">
        {panel?.resources?.map((r: any) => (
          <a key={r.slug} href={basePath + '/' + r.slug}
             className="block p-6 bg-white dark:bg-gray-800 rounded-xl border border-gray-200 dark:border-gray-700 hover:border-indigo-300 dark:hover:border-indigo-600 transition">
            <h3 className="font-semibold text-gray-900 dark:text-gray-100">{r.label}</h3>
            <p className="text-sm text-gray-500 dark:text-gray-400 mt-1">Manage {r.label.toLowerCase()}</p>
          </a>
        ))}
      </div>
    </>
  )
}
`)

  // ── Slug (resource index OR custom page) ───────────────────
  // Single route for all 2-segment URLs — server disambiguates via pageType in viewProps.
  // Avoids the "two routes match on client" problem that breaks SPA navigation.
  writeIfChanged(path.join(outDir, 'slug', '+route.ts'), `// AUTO-GENERATED by @pilotiq/pilotiq — do not edit.
import type { RouteSync } from 'vike/types'
import { PilotiqRegistry } from '@pilotiq/pilotiq/registry'

export const route: RouteSync = (pageContext) => {
  const parts = pageContext.urlPathname.split('/').filter(Boolean)
  if (parts.length !== 2) return false
  // Don't match built-in slugs (theme editor, etc.)
  if (parts[1] === 'theme') return false
  if (import.meta.env.SSR && !PilotiqRegistry.findByPath('/' + parts[0])) return false
  return { routeParams: { basePath: parts[0], slug: parts[1] } }
}
`)
  writeIfChanged(path.join(outDir, 'slug', '+data.ts'), dataStub)
  writeIfChanged(path.join(outDir, 'slug', '+Page.tsx'), `// AUTO-GENERATED by @pilotiq/pilotiq — do not edit.
import { usePageContext } from 'vike-react/usePageContext'
import { SchemaRenderer } from '@pilotiq/pilotiq/react'

export default function SlugPage() {
  const ctx = usePageContext() as unknown as { viewProps?: Record<string, unknown> }
  const vp = ctx.viewProps as any ?? {}

  // Server sets pageType: 'resource' or 'page'
  if (vp.pageType === 'page') {
    return <SchemaRenderer elements={vp.schemaData ?? []} />
  }

  // Resource index (default)
  const { basePath, resource, columns } = vp
  return (
    <>
      <div className="flex items-center justify-between mb-6">
        <h1 className="text-2xl font-bold">{resource?.label}</h1>
        <a href={basePath + '/' + resource?.slug + '/create'}
           className="px-4 py-2 bg-primary text-primary-foreground text-sm font-medium rounded-lg hover:bg-primary/90 transition">
          Create {resource?.labelSingular}
        </a>
      </div>
      <div className="rounded-xl border bg-card overflow-hidden">
        <table className="w-full text-sm">
          <thead className="bg-muted border-b">
            <tr>
              {columns?.map((col: any) => (
                <th key={col.name} className="px-4 py-3 text-left text-xs font-medium text-muted-foreground uppercase tracking-wider">
                  {col.label}
                </th>
              ))}
            </tr>
          </thead>
          <tbody>
            <tr>
              <td colSpan={columns?.length ?? 1} className="px-4 py-12 text-center text-muted-foreground">
                No records yet.
              </td>
            </tr>
          </tbody>
        </table>
      </div>
    </>
  )
}
`)

  // ── Resource Create ───────────────────────────────────────
  writeIfChanged(path.join(outDir, 'resource-create', '+route.ts'), `// AUTO-GENERATED by @pilotiq/pilotiq — do not edit.
import type { RouteSync } from 'vike/types'
import { PilotiqRegistry } from '@pilotiq/pilotiq/registry'

export const route: RouteSync = (pageContext) => {
  const parts = pageContext.urlPathname.split('/').filter(Boolean)
  if (parts.length !== 3 || parts[2] !== 'create') return false
  if (import.meta.env.SSR && !PilotiqRegistry.findByPath('/' + parts[0])) return false
  return { routeParams: { basePath: parts[0], slug: parts[1] } }
}
`)
  writeIfChanged(path.join(outDir, 'resource-create', '+data.ts'), dataStub)

  // ── Resource Edit ─────────────────────────────────────────
  writeIfChanged(path.join(outDir, 'resource-edit', '+route.ts'), `// AUTO-GENERATED by @pilotiq/pilotiq — do not edit.
import type { RouteSync } from 'vike/types'
import { PilotiqRegistry } from '@pilotiq/pilotiq/registry'

export const route: RouteSync = (pageContext) => {
  const parts = pageContext.urlPathname.split('/').filter(Boolean)
  if (parts.length !== 4 || parts[3] !== 'edit') return false
  if (import.meta.env.SSR && !PilotiqRegistry.findByPath('/' + parts[0])) return false
  return { routeParams: { basePath: parts[0], slug: parts[1], id: parts[2] } }
}
`)
  writeIfChanged(path.join(outDir, 'resource-edit', '+data.ts'), dataStub)

  // Create and Edit share the same form page component
  const formPage = `// AUTO-GENERATED by @pilotiq/pilotiq — do not edit.
import { usePageContext } from 'vike-react/usePageContext'

export default function ResourceForm() {
  const ctx = usePageContext() as unknown as { viewProps?: Record<string, unknown> }
  const { basePath, resource, fields, mode } = ctx.viewProps as any ?? {}
  const title = mode === 'create' ? 'Create ' + resource?.label : 'Edit ' + resource?.label
  return (
    <>
      <h1 className="text-2xl font-bold mb-6">{title}</h1>
      <div className="rounded-xl border bg-card p-6">
        <form className="space-y-6">
          {fields?.map((field: any) => (
            <div key={field.name}>
              <label className="block text-sm font-medium mb-1">
                {field.label}{field.required && <span className="text-destructive ml-1">*</span>}
              </label>
              {field.fieldType === 'textarea' ? (
                <textarea name={field.name} placeholder={field.placeholder} rows={4}
                  className="w-full px-3 py-2 border rounded-lg text-sm bg-background focus:ring-2 focus:ring-ring outline-none" />
              ) : (
                <input name={field.name}
                  type={field.fieldType === 'email' ? 'email' : field.fieldType === 'number' ? 'number' : field.fieldType === 'date' ? 'date' : 'text'}
                  placeholder={field.placeholder} readOnly={field.readonly} required={field.required}
                  className="w-full px-3 py-2 border rounded-lg text-sm bg-background focus:ring-2 focus:ring-ring outline-none" />
              )}
            </div>
          ))}
          <div className="flex gap-3 pt-4 border-t">
            <button type="submit" className="px-4 py-2 bg-primary text-primary-foreground text-sm font-medium rounded-lg hover:bg-primary/90 transition">
              {mode === 'create' ? 'Create' : 'Save'}
            </button>
            <a href={basePath + '/' + resource?.slug}
               className="px-4 py-2 text-sm text-muted-foreground hover:text-foreground transition">
              Cancel
            </a>
          </div>
        </form>
      </div>
    </>
  )
}
`
  writeIfChanged(path.join(outDir, 'resource-create', '+Page.tsx'), formPage)
  writeIfChanged(path.join(outDir, 'resource-edit', '+Page.tsx'), formPage)

  // NOTE: Custom pages are handled by the 'slug' route above (pageType: 'page')

  // ── Theme Editor ─────────────────────────────────────────
  writeIfChanged(path.join(outDir, 'theme', '+route.ts'), `// AUTO-GENERATED by @pilotiq/pilotiq — do not edit.
import type { RouteSync } from 'vike/types'
import { PilotiqRegistry } from '@pilotiq/pilotiq/registry'

export const route: RouteSync = (pageContext) => {
  const parts = pageContext.urlPathname.split('/').filter(Boolean)
  if (parts.length !== 2 || parts[1] !== 'theme') return false
  if (import.meta.env.SSR) {
    const panel = PilotiqRegistry.findByPath('/' + parts[0])
    if (!panel) return false
    // Only match if themeEditor is enabled
    if (!panel.getConfig().themeEditor) return false
  }
  return { routeParams: { basePath: parts[0] } }
}
`)
  writeIfChanged(path.join(outDir, 'theme', '+data.ts'), dataStub)
  writeIfChanged(path.join(outDir, 'theme', '+Page.tsx'), `// AUTO-GENERATED by @pilotiq/pilotiq — do not edit.
import { usePageContext } from 'vike-react/usePageContext'
import { navigate } from 'vike/client/router'
import { ThemeSettingsPage } from '@pilotiq/pilotiq/react'

const handleNavigate = (url: string) => navigate(url, { overwriteLastHistoryEntry: true, scrollToTop: false } as any)

export default function ThemeEditorPage() {
  const ctx = usePageContext() as unknown as { viewProps?: Record<string, unknown> }
  const { basePath, themeConfig } = ctx.viewProps as any ?? {}
  return <ThemeSettingsPage panelPath={basePath} initialConfig={themeConfig} onNavigate={handleNavigate} />
}
`)
}

export function pilotiq(): Plugin {
  const cwd = process.cwd()
  const pagesRoot = path.join(cwd, 'pages')

  // Generate at construction time — before Vike scans pages/
  generatePages(pagesRoot)

  return {
    name: 'pilotiq:pages',
    enforce: 'pre',
    buildStart() {
      generatePages(pagesRoot)
    },
  }
}
