/**
 * Vite plugin that generates Vike page stubs for @pilotiq/pilotiq.
 *
 * Stubs are written at plugin construction time (before Vike scans pages/).
 * They use route functions that check PilotiqRegistry at request time, so
 * they work for any number of registered panels without regeneration.
 *
 * The plugin also reads the user's panel module(s) (default
 * `app/Pilotiq/AdminPanel`) and emits `pages/(pilotiq)/_components.ts`,
 * a re-export manifest of every Resource/Global/Page class registered
 * across all panels. The auto-gen `+Layout.tsx` imports the manifest
 * so component-typed icons (`Resource.icon = SomeIcon`) resolve at
 * render time.
 */
import fs from 'node:fs'
import path from 'node:path'
import { createJiti } from 'jiti'
import type { Plugin } from 'vite'

export interface PilotiqVitePluginOptions {
  /**
   * Path(s) to module(s) exporting `Pilotiq` instances. The plugin
   * imports each path and walks `panel.getConfig().resources / globals /
   * pages` to build the component manifest.
   *
   * Paths are resolved relative to the Vite config's project root.
   * Defaults to `['./app/Pilotiq/AdminPanel']` (the convention used by
   * the playgrounds). Override only if your panel module lives elsewhere.
   *
   * Panel files must be import-safe — top-level code must not run
   * server-only logic (db queries, `node:fs`, etc.). Builder calls and
   * class definitions are fine.
   */
  panels?: string | string[]
}

function writeIfChanged(filePath: string, contents: string): void {
  fs.mkdirSync(path.dirname(filePath), { recursive: true })
  if (fs.existsSync(filePath)) {
    const existing = fs.readFileSync(filePath, 'utf8')
    if (existing === contents) return
  }
  fs.writeFileSync(filePath, contents)
}

